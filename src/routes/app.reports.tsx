import { createFileRoute, Link } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "@/hooks/useAuth";
import { Card, PageHeader } from "@/components/app/AppShell";
import { ArrowLeft, Download } from "lucide-react";
import { jsPDF } from "jspdf";

export const Route = createFileRoute("/app/reports")({
  component: ReportsPage,
});

function daysAgo(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString().slice(0, 10);
}

function ReportsPage() {
  const { user } = useAuth();

  const { data } = useQuery({
    queryKey: ["weekly-report", user?.id],
    enabled: !!user,
    queryFn: async () => {
      const since = daysAgo(6);
      const sinceISO = new Date(since + "T00:00:00Z").toISOString();
      const [w, m, p, meas] = await Promise.all([
        supabase.from("workouts").select("date,title,duration_min,workout_sets(reps,weight_kg)")
          .gte("date", since).order("date"),
        supabase.from("meals").select("eaten_at,kcal,protein_g,carbs_g,fat_g")
          .gte("eaten_at", sinceISO),
        supabase.from("protocol_items").select("date,done").gte("date", since),
        supabase.from("measurements").select("taken_at,weight_kg,body_fat_pct")
          .gte("taken_at", sinceISO).order("taken_at"),
      ]);

      const meals = m.data ?? [];
      const totalKcal = meals.reduce((a, x) => a + (x.kcal ?? 0), 0);
      const totalProtein = meals.reduce((a, x) => a + Number(x.protein_g ?? 0), 0);
      const workouts = w.data ?? [];
      const totalVolume = workouts.reduce((a, wk) => {
        const sets = (wk as any).workout_sets ?? [];
        return a + sets.reduce((s: number, st: any) => s + (Number(st.reps ?? 0) * Number(st.weight_kg ?? 0)), 0);
      }, 0);
      const protocol = p.data ?? [];
      const rites = protocol.length ? Math.round((protocol.filter((r) => r.done).length / protocol.length) * 100) : 0;
      const measurements = meas.data ?? [];

      return {
        rangeStart: since, rangeEnd: daysAgo(0),
        workoutCount: workouts.length,
        avgKcal: Math.round(totalKcal / 7),
        avgProtein: Math.round(totalProtein / 7),
        totalVolumeKg: Math.round(totalVolume),
        ritePct: rites,
        workouts, meals, measurements,
      };
    },
  });

  function downloadPdf() {
    if (!data) return;
    const doc = new jsPDF({ unit: "pt", format: "a4" });
    const w = doc.internal.pageSize.getWidth();
    let y = 56;
    doc.setFont("helvetica", "bold"); doc.setFontSize(20);
    doc.text("ETHEREAL BODYLABS", 40, y); y += 22;
    doc.setFont("helvetica", "normal"); doc.setFontSize(11); doc.setTextColor(120);
    doc.text(`Weekly report · ${data.rangeStart} → ${data.rangeEnd}`, 40, y); y += 26;

    doc.setTextColor(20); doc.setFont("helvetica", "bold"); doc.setFontSize(13);
    doc.text("Summary", 40, y); y += 16;
    doc.setFont("helvetica", "normal"); doc.setFontSize(11);
    const rows: [string, string][] = [
      ["Workouts", `${data.workoutCount}`],
      ["Avg kcal / day", `${data.avgKcal}`],
      ["Avg protein / day", `${data.avgProtein} g`],
      ["Training volume", `${data.totalVolumeKg} kg·reps`],
      ["Protocol adherence", `${data.ritePct}%`],
    ];
    rows.forEach(([k, v]) => { doc.text(k, 40, y); doc.text(v, w - 40, y, { align: "right" }); y += 16; });

    y += 12; doc.setFont("helvetica", "bold"); doc.setFontSize(13);
    doc.text("Sessions", 40, y); y += 14;
    doc.setFont("helvetica", "normal"); doc.setFontSize(10);
    (data.workouts as any[]).forEach((wk) => {
      const sets = (wk.workout_sets ?? []).length;
      doc.text(`${wk.date}  ${wk.title ?? "Session"}  ·  ${wk.duration_min ?? "—"} min  ·  ${sets} sets`, 40, y);
      y += 13; if (y > 780) { doc.addPage(); y = 56; }
    });

    if (data.measurements.length) {
      y += 10; doc.setFont("helvetica", "bold"); doc.setFontSize(13);
      doc.text("Measurements", 40, y); y += 14;
      doc.setFont("helvetica", "normal"); doc.setFontSize(10);
      (data.measurements as any[]).forEach((mm) => {
        doc.text(`${new Date(mm.taken_at).toISOString().slice(0, 10)}  ${mm.weight_kg ?? "—"} kg  ${mm.body_fat_pct ?? "—"}%`, 40, y);
        y += 13;
      });
    }

    doc.setTextColor(140); doc.setFontSize(9);
    doc.text("Generated by ETHEREAL BODYLABS · Personal data — do not share.", 40, 820);
    doc.save(`ebl-weekly-${data.rangeStart}.pdf`);
  }

  return (
    <div>
      <Link to="/app" className="inline-flex items-center gap-1 text-xs text-muted-foreground mb-3">
        <ArrowLeft className="size-3.5" /> Today
      </Link>
      <PageHeader eyebrow="Insights" title="Weekly report"
        action={
          <button onClick={downloadPdf} className="rounded-lg bg-primary text-primary-foreground px-3 py-1.5 text-xs font-medium inline-flex items-center gap-1">
            <Download className="size-3.5" /> PDF
          </button>
        } />
      {data ? (
        <div className="space-y-3">
          <div className="grid grid-cols-2 gap-2">
            <Metric label="Workouts" value={String(data.workoutCount)} />
            <Metric label="Avg kcal" value={String(data.avgKcal)} />
            <Metric label="Avg protein" value={`${data.avgProtein}g`} />
            <Metric label="Volume" value={`${data.totalVolumeKg}kg·reps`} />
            <Metric label="Rite adherence" value={`${data.ritePct}%`} />
          </div>

          <Card>
            <div className="font-mono text-[10px] uppercase tracking-[0.16em] text-muted-foreground mb-2">Sessions</div>
            {(data.workouts as any[]).length === 0
              ? <div className="text-sm text-muted-foreground">No sessions logged this week.</div>
              : (data.workouts as any[]).map((w, i) => (
                <div key={i} className="flex justify-between text-sm py-1 border-b border-border/40 last:border-0">
                  <span>{w.date} · {w.title ?? "Session"}</span>
                  <span className="font-mono text-muted-foreground">{w.duration_min ?? "—"}m</span>
                </div>
              ))}
          </Card>
        </div>
      ) : (
        <div className="text-sm text-muted-foreground">Compiling…</div>
      )}
    </div>
  );
}
function Metric({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-2xl glass p-4">
      <div className="font-mono text-[10px] uppercase tracking-wider text-muted-foreground">{label}</div>
      <div className="mt-1 text-xl font-semibold tabular-nums">{value}</div>
    </div>
  );
}
